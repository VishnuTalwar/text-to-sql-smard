"""
Catalog v2b: catalog v2a plus plain descriptions of the metrik and preiszone values.

This is ablation row v2b (on top of v2a). It is built from schema_catalog_v2a.CATALOG
(which is itself the original catalog with the reworded Kernenergie note), and changes
only these things:
  - verbrauch: adds "value_meanings" for the metrik values, and replaces the verbrauch
    version of the Pumpspeicher quirk (the erzeugung version stays as it is).
  - preise: adds "value_meanings" for the preiszone values.
Everything else is identical by construction. No existing file is modified.

"value_meanings" is a new key that the old renderer ignores; prompt_template_v2b.py
is the renderer that shows it.
"""

import copy

from schema_catalog_v2a import CATALOG as _BASE_CATALOG

OLD_VERBRAUCH_PUMPSPEICHER_NOTE = (
    "Pumpspeicher means opposite things in the two tables — "
    "generation (releasing water) in erzeugung, "
    "consumption (pumping water up) in verbrauch. Do not conflate."
)

NEW_VERBRAUCH_PUMPSPEICHER_NOTE = (
    "'Hydro pumped storage' here is electricity used to pump water uphill. "
    "In erzeugung, 'Pumpspeicher' is the opposite: electricity generated by releasing that water. "
    "Do not mix them up."
)

METRIK_MEANINGS = [
    "grid load: total electricity consumption. Use this for general questions about consumption, demand or load.",
    "Hydro pumped storage: electricity used to pump water up into pumped-storage reservoirs.",
    "Grid load incl. hydro pumped storage: grid load plus Hydro pumped storage.",
    "Residual load: grid load minus wind (onshore and offshore) and solar generation; the demand left for other power plants. Can be negative.",
]

PREISZONE_MEANINGS = [
    "Deutschland/Luxemburg: the German price zone (shared with Luxembourg). Use this for \"the German price\" or \"the price in Germany\".",
    "∅ Anrainer DE/LU: not a market zone. It is the average price of Germany's 11 neighbouring zones: "
    "Belgien, Dänemark 1, Dänemark 2, Frankreich, Niederlande, Norwegen 2, Österreich, Polen, Schweden 4, "
    "Schweiz, Tschechien. Leave it out when ranking or comparing zones.",
    "DE/AT/LU: the old joint zone, empty for the whole dataset (see the quirk below).",
    "All other values are individual market zones.",
]

CATALOG: dict[str, dict] = copy.deepcopy(_BASE_CATALOG)

# verbrauch: replace the Pumpspeicher quirk (verbrauch only) ...
_verbrauch_quirks = CATALOG["verbrauch"]["quirks"]
if _verbrauch_quirks.count(OLD_VERBRAUCH_PUMPSPEICHER_NOTE) != 1:
    raise RuntimeError("verbrauch no longer contains the expected Pumpspeicher quirk exactly once.")
_verbrauch_quirks[_verbrauch_quirks.index(OLD_VERBRAUCH_PUMPSPEICHER_NOTE)] = NEW_VERBRAUCH_PUMPSPEICHER_NOTE

# ... and add the value meanings.
CATALOG["verbrauch"]["value_meanings"] = {"metrik": METRIK_MEANINGS}
CATALOG["preise"]["value_meanings"] = {"preiszone": PREISZONE_MEANINGS}
